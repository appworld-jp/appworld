鍋にだし汁、鶏肉、にんじんを入れてアクを取りながら火を通し、調味料で味をととのえます。
もちを焼いて（ゆでても）お椀に入れ、小松菜、かまぼこを入れて熱い汁を注ぎ、三つ葉を添えます。

